// Main
// ═══════════════════════════════════════
exports.main = async (event, context) => {
  const now = Date.now()
  const force = event.force === true
  const results = { categories: 0, items: 0 }
  const { OPENID } = cloud.getWXContext()
  const bySecret = isSecretValid(event.secret)

  if (!OPENID && !bySecret) {
    return { code: -1, message: '获取用户身份失败（控制台测试请使用 secret 参数）' }
  }

  if (!bySecret && !(await isOperator(OPENID))) {
    return {
      code: 403,
      message: '无权限：仅管理员可初始化。请配置 init 云函数环境变量 ADMIN_OPENIDS=<你的 openid>，或在控制台测试时传 secret'
    }
  }

  try {
    // ── Categories ──
    const { total: catCount } = await db.collection('faq_categories').count()
    if (catCount > 0 && !force) {
      return { code: 0, data: { message: '已初始化过。使用 force:true 强制重建', ...results } }
    }
    if (force) {
      const { data: oldCats } = await db.collection('faq_categories').get()
      for (const c of oldCats) {
        await db.collection('faq_items').where({ categoryId: c._id }).remove()
        await db.collection('faq_categories').doc(c._id).remove()
      }
    }

    const catIds = []
    for (const cat of CATS) {
      const r = await db.collection('faq_categories').add({
        data: { ...cat, isActive: true, createdAt: now, updatedAt: now }
      })
      catIds.push(r._id)
      results.categories++
    }

    // ── Items ──
    for (const item of ITEMS) {
      const content = wrapContent(item.t, item.d)
      await db.collection('faq_items').add({
        data: {
          categoryId: catIds[item.c],
          title: item.t,
          summary: item.s,
          content: content,
          contentHtml: md2html(content),
          tags: item.g,
          sortOrder: item.sortOrder || 0,
          isPinned: !!item.p,
          isActive: true,
          viewCount: Math.floor(Math.random() * 300) + 5,
          createdAt: now - Math.floor(Math.random() * 86400000 * 60),
          updatedAt: now
        }
      })
      results.items++
    }

    // ── Admin whitelist ──
    // 把当前初始化者写入 admins（openid 白名单），login 云函数据此返回 isAdmin。
    // 不再生成默认口令账号；控制台 secret 模式没有 openid，跳过绑定。
    if (OPENID) {
      try {
        const { data: existed } = await db.collection('admins')
          .where({ openid: OPENID })
          .get()
        if (existed.length > 0) {
          await db.collection('admins').doc(existed[0]._id).update({
            data: { isActive: true, updatedAt: now }
          })
        } else {
          await db.collection('admins').add({
            data: {
              openid: OPENID,
              displayName: '管理员',
              isActive: true,
              createdAt: now,
              updatedAt: now
            }
          })
        }
      } catch (e) {
        console.error('[init] failed to bind admin:', e)
      }
    }

    return { code: 0, data: { message: '初始化完成 (' + results.items + '条FAQ)', ...results } }
  } catch (err) {
    console.error('[init] error:', err)
    return { code: -1, message: '初始化失败: ' + err.message }
  }
}
