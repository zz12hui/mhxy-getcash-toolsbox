function wrapContent(title, body) {
  return '# ' + title + '\n\n' + (body || '')
}

function md2html(md) {
  return (md || '')
    .replace(/^### (.+)$/gm, '<h3>$1</h3>')
    .replace(/^## (.+)$/gm, '<h2>$1</h2>')
    .replace(/^# (.+)$/gm, '<h1>$1</h1>')
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/\n- /g, '<br/>- ')
    .replace(/\n/g, '<br/>')
}

